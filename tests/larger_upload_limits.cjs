const fs=require('node:fs');
const assert=require('node:assert/strict');
const ext=fs.readFileSync('app/extensions.py','utf8');
const moments=fs.readFileSync('app/moments.py','utf8');
const client=fs.readFileSync('app/web/app.js','utf8');
const editor=fs.readFileSync('app/web/chat-enhancements.js','utf8');
const stories=fs.readFileSync('app/web/moments.js','utf8');
assert(ext.includes('MAX_UPLOAD = 25 * 1024 * 1024'),'Nonvideo server cap must be 25 MiB');
assert(ext.includes('MAX_VIDEO_UPLOAD = 50 * 1024 * 1024'),'Video server cap must be 50 MiB');
assert(moments.includes('MEDIA_LIMIT=24*1024*1024'),'Moment cap must be 24 MiB');
assert(client.includes('?50:25)*1024*1024'),'Direct attachment upload cap mismatch');
assert(editor.includes('?50:25;'),'Media editor cap mismatch');
assert(editor.includes('?50:25)*1024*1024'),'Edited attachment cap mismatch');
assert(stories.includes('file.size>24*1024*1024'),'Moments client cap mismatch');
assert(client.includes('xhr.upload.onprogress=event=>'),'Chat attachment upload must show real progress');
assert(client.includes('xhr.withCredentials=true'),'Same-origin account should authorize XHR');
assert(client.includes('setMediaProgress'),'Chat attachment progress must be visible');
assert(ext.includes('if len(blob)>MAX_VIDEO_UPLOAD'),'Download guard must accept updated video size');
console.log('LARGER_UPLOAD_LIMITS_PASS: matching client/server limits, real progress, private download guard');
